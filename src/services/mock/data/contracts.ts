import type { Contract, ContractPayment } from '@/domains/contracts/types';
import { auditOf } from './audit';
import { APP, CON, PERSON, PRJ, VENDOR } from './ids';
import { seedId } from './sequence';

type PaymentSeed = [
  dueDate: string,
  amount: number,
  status: string,
  description?: string,
  invoiceNumber?: string,
  paidDate?: string,
];

type ContractSeed = Omit<Contract, 'code' | 'audit' | 'payments' | 'relatedApplicationIds'> & {
  relatedApplicationIds?: number[];
  payments?: PaymentSeed[];
  created: string;
};

function contract({
  payments = [],
  created,
  relatedApplicationIds = [],
  ...seed
}: ContractSeed): Contract {
  return {
    ...seed,
    relatedApplicationIds,
    code: `SZL-${String(seed.id).padStart(4, '0')}`,
    payments: payments.map(
      ([
        dueDate,
        amount,
        status,
        description = '',
        invoiceNumber = '',
        paidDate,
      ]): ContractPayment => ({
        id: seedId('contractPayments'),
        dueDate,
        amount,
        status,
        description,
        invoiceNumber,
        paidDate: paidDate ?? null,
      }),
    ),
    audit: auditOf({ created, updated: '2026-09-15', reviewed: null, by: PERSON.zeynepCelik }),
  };
}

