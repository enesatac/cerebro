CREATE TABLE projects (
  id                          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                        VARCHAR2(30 CHAR)  NOT NULL,
  name                        VARCHAR2(200 CHAR) NOT NULL,
  short_name                  VARCHAR2(200 CHAR),
  description                 CLOB,
  objective                   CLOB,
  scope                       CLOB,
  out_of_scope                CLOB,
  type                        VARCHAR2(60 CHAR)  NOT NULL,
  priority                    VARCHAR2(60 CHAR)  NOT NULL,
  status                      VARCHAR2(60 CHAR)  NOT NULL,
  health                      VARCHAR2(60 CHAR)  NOT NULL,
  confidentiality             VARCHAR2(60 CHAR)  NOT NULL,
  tags                        CLOB,                    -- JSON array of strings
  business_unit_id            NUMBER(19)         CONSTRAINT fk_projects_unit REFERENCES business_units (id),
  planned_start_date          DATE,
  actual_start_date           DATE,
  planned_end_date            DATE,
  actual_end_date             DATE,
  progress_percentage         NUMBER(3)          NOT NULL,
  current_phase               VARCHAR2(60 CHAR)  NOT NULL,
  latest_status_summary       CLOB,
  next_steps                  CLOB,
  -- Project.financials (NULL currency = no financial information recorded)
  currency                    VARCHAR2(10 CHAR),
  budget                      NUMBER(18, 2),
  actual_cost                 NUMBER(18, 2),
  forecast_cost               NUMBER(18, 2),
  created_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_by_person_id        NUMBER(19)         REFERENCES people (id),
  updated_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by_person_id        NUMBER(19)         REFERENCES people (id),
  last_reviewed_at            TIMESTAMP(3) WITH TIME ZONE,
  last_reviewed_by_person_id  NUMBER(19)         REFERENCES people (id),
  CONSTRAINT uq_projects_code UNIQUE (code),
  CONSTRAINT ck_projects_code CHECK (REGEXP_LIKE(code, '^[A-Z0-9-]+$')),
  CONSTRAINT ck_projects_progress CHECK (progress_percentage BETWEEN 0 AND 100),
  CONSTRAINT ck_projects_planned CHECK (planned_end_date IS NULL OR planned_start_date IS NULL OR planned_end_date >= planned_start_date),
  CONSTRAINT ck_projects_actual CHECK (actual_end_date IS NULL OR actual_start_date IS NULL OR actual_end_date >= actual_start_date)
);
CREATE INDEX ix_projects_unit ON projects (business_unit_id);

