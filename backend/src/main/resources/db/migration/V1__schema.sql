-- =====================================================================================================
-- Cerebro — relational schema (Oracle Database 19c and later)
--
-- The TypeScript domain model (frontend/src/domains/*/types) maps onto these tables:
--   * Every table has a surrogate key `id` from its own identity sequence (`EntityId` in the code).
--     New rows leave `id` out and take the next value, stored child rows sent back with their id
--     (`Draft<T>` in the code) keep it. Keys are never reused after deletes.
--   * Rows edited as part of an aggregate (environments, milestones, role assignments…) are child
--     tables, many-to-many links are tables with a unique pair.
--   * Enumerated values are rows of `master_data_items`, records store the stable `code`, checked by
--     the application on every write (`MasterCodes`).
--   * Booleans are NUMBER(1) 0/1, lists of strings (tags…) are JSON arrays in a CLOB.
--   * Oracle stores '' as NULL: optional text columns are nullable and read back as ''.
--   * Audit columns reference `people` (NULL when the acting account is not linked to a person).
--
-- Written for 19c: no BOOLEAN columns, no IF [NOT] EXISTS, no multi-row VALUES. Every index and
-- constraint that matters has a name. Overlap rules (one leave per person and day, one allocation
-- per person, project and day) are enforced by the application under a row lock on the person.
-- =====================================================================================================

-- -----------------------------------------------------------------------------------------------------
-- Master data
-- -----------------------------------------------------------------------------------------------------

CREATE TABLE master_data_items (
  id           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list_key     VARCHAR2(60 CHAR)   NOT NULL,          -- MASTER_DATA_LIST_KEYS, e.g. 'applicationTypes'
  code         VARCHAR2(60 CHAR)   NOT NULL,
  label        VARCHAR2(200 CHAR)  NOT NULL,
  description  VARCHAR2(1000 CHAR),
  variant      VARCHAR2(20 CHAR),                     -- badge colour, NULL for plain-text lists
  active       NUMBER(1)           DEFAULT 1 NOT NULL,
  sort_order   NUMBER(10)          NOT NULL,          -- display order within the list
  CONSTRAINT ck_mdi_code CHECK (REGEXP_LIKE(code, '^[A-Za-z0-9]+([-_][A-Za-z0-9]+)*$')),
  CONSTRAINT ck_mdi_active CHECK (active IN (0, 1)),
  CONSTRAINT uq_mdi_code UNIQUE (list_key, code),
  CONSTRAINT uq_mdi_label UNIQUE (list_key, label)
);

