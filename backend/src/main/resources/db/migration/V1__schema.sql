CREATE TABLE business_units (
  id              NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            VARCHAR2(30 CHAR)  NOT NULL,
  name            VARCHAR2(200 CHAR) NOT NULL,
  description     VARCHAR2(1000 CHAR),
  head_person_id  NUMBER(19),                          -- FK added below (people ↔ business_units cycle)
  CONSTRAINT uq_business_units_code UNIQUE (code),
  CONSTRAINT uq_business_units_name UNIQUE (name)
);

CREATE TABLE people (
  id                NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name         VARCHAR2(200 CHAR) NOT NULL,
  job_title         VARCHAR2(200 CHAR),
  email             VARCHAR2(254 CHAR) NOT NULL,
  business_unit_id  NUMBER(19)         CONSTRAINT fk_people_unit REFERENCES business_units (id) ON DELETE SET NULL,
  location          VARCHAR2(200 CHAR),
  CONSTRAINT uq_people_email UNIQUE (email)
);

ALTER TABLE business_units
  ADD CONSTRAINT fk_business_units_head FOREIGN KEY (head_person_id) REFERENCES people (id);

CREATE TABLE user_accounts (
  id                          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name                VARCHAR2(200 CHAR) NOT NULL,
  email                       VARCHAR2(254 CHAR) NOT NULL,
  email_key                   VARCHAR2(254 CHAR) GENERATED ALWAYS AS (LOWER(email)),
  person_id                   NUMBER(19)         CONSTRAINT fk_user_accounts_person REFERENCES people (id),
  active                      NUMBER(1)          DEFAULT 1 NOT NULL,
  last_sign_in_at             TIMESTAMP(3) WITH TIME ZONE,
  created_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_by_person_id        NUMBER(19)         REFERENCES people (id),
  updated_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by_person_id        NUMBER(19)         REFERENCES people (id),
  last_reviewed_at            TIMESTAMP(3) WITH TIME ZONE,
  last_reviewed_by_person_id  NUMBER(19)         REFERENCES people (id),
  CONSTRAINT ck_user_accounts_active CHECK (active IN (0, 1)),
  CONSTRAINT uq_user_accounts_email UNIQUE (email_key)
);

-- Access control. Privileges are a fixed catalogue (the application checks them by code), roles
-- bundle privileges and are administrable, a user's access is the union of their roles.
CREATE TABLE access_privileges (
  code          VARCHAR2(60 CHAR)   PRIMARY KEY,       -- 'projects:edit'
  module        VARCHAR2(40 CHAR)   NOT NULL,
  access_level  VARCHAR2(10 CHAR)   NOT NULL,
  description   VARCHAR2(400 CHAR)  NOT NULL,
  CONSTRAINT ck_access_privileges_code CHECK (REGEXP_LIKE(code, '^[a-zA-Z]+:(view|edit|delete)$')),
  CONSTRAINT ck_access_privileges_level CHECK (access_level IN ('view', 'edit', 'delete')),
  CONSTRAINT uq_access_privileges UNIQUE (module, access_level)
);

CREATE TABLE roles (
  id                          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                        VARCHAR2(80 CHAR)  NOT NULL,
  name_key                    VARCHAR2(80 CHAR)  GENERATED ALWAYS AS (LOWER(name)),
  description                 VARCHAR2(300 CHAR),
  -- The system administrator role: every privilege, cannot be changed or deleted, only one.
  system_role                 NUMBER(1)          DEFAULT 0 NOT NULL,
  system_key                  NUMBER(1)          GENERATED ALWAYS AS (CASE WHEN system_role = 1 THEN 1 END),
  created_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_by_person_id        NUMBER(19)         REFERENCES people (id),
  updated_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by_person_id        NUMBER(19)         REFERENCES people (id),
  last_reviewed_at            TIMESTAMP(3) WITH TIME ZONE,
  last_reviewed_by_person_id  NUMBER(19)         REFERENCES people (id),
  CONSTRAINT ck_roles_system CHECK (system_role IN (0, 1)),
  CONSTRAINT uq_roles_name UNIQUE (name_key),
  CONSTRAINT uq_roles_system UNIQUE (system_key)
);

-- Stored with the implied lower levels (edit ⇒ view, delete ⇒ edit), as the application saves them.
CREATE TABLE role_privileges (
  role_id         NUMBER(19)        NOT NULL CONSTRAINT fk_role_privileges_role REFERENCES roles (id) ON DELETE CASCADE,
  privilege_code  VARCHAR2(60 CHAR) NOT NULL CONSTRAINT fk_role_privileges_code REFERENCES access_privileges (code) ON DELETE CASCADE,
  CONSTRAINT pk_role_privileges PRIMARY KEY (role_id, privilege_code)
);

-- A role held by users cannot be deleted, at least one active user keeps the system role (both
-- enforced by the application, the first also by the foreign key).
CREATE TABLE user_roles (
  user_account_id  NUMBER(19) NOT NULL CONSTRAINT fk_user_roles_account REFERENCES user_accounts (id) ON DELETE CASCADE,
  role_id          NUMBER(19) NOT NULL CONSTRAINT fk_user_roles_role REFERENCES roles (id),
  sort_order       NUMBER(10) DEFAULT 0 NOT NULL,      -- the order the roles were given in
  CONSTRAINT pk_user_roles PRIMARY KEY (user_account_id, role_id)
);
CREATE INDEX ix_user_roles_role ON user_roles (role_id);

