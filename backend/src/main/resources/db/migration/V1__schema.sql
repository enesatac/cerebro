CREATE INDEX ix_attachments_project ON attachments (project_id);
CREATE INDEX ix_attachments_team ON attachments (team_id);
CREATE INDEX ix_attachments_tech ON attachments (technology_id);
CREATE INDEX ix_attachments_risk ON attachments (risk_id);
CREATE INDEX ix_attachments_escalation ON attachments (escalation_id);
CREATE INDEX ix_attachments_decision ON attachments (decision_id);
CREATE INDEX ix_attachments_demand ON attachments (demand_id);
CREATE INDEX ix_attachments_contract ON attachments (contract_id);

