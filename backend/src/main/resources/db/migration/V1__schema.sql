-- -----------------------------------------------------------------------------------------------------
-- Attachments (files on records): metadata here, bytes in attachment_contents
-- -----------------------------------------------------------------------------------------------------

-- One nullable foreign key per owner type keeps referential integrity (the domain's
-- `owner: { type, id }`), exactly one is set. Files go with their record (ON DELETE CASCADE).
CREATE TABLE attachments (                           -- Attachment
  id                          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id              NUMBER(19)         CONSTRAINT fk_attachments_app REFERENCES applications (id) ON DELETE CASCADE,
  project_id                  NUMBER(19)         CONSTRAINT fk_attachments_project REFERENCES projects (id) ON DELETE CASCADE,
  team_id                     NUMBER(19)         CONSTRAINT fk_attachments_team REFERENCES teams (id) ON DELETE CASCADE,
  technology_id               NUMBER(19)         CONSTRAINT fk_attachments_tech REFERENCES technologies (id) ON DELETE CASCADE,
  risk_id                     NUMBER(19)         CONSTRAINT fk_attachments_risk REFERENCES risks (id) ON DELETE CASCADE,
  escalation_id               NUMBER(19)         CONSTRAINT fk_attachments_escalation REFERENCES escalations (id) ON DELETE CASCADE,
  decision_id                 NUMBER(19)         CONSTRAINT fk_attachments_decision REFERENCES decisions (id) ON DELETE CASCADE,
  demand_id                   NUMBER(19)         CONSTRAINT fk_attachments_demand REFERENCES demands (id) ON DELETE CASCADE,
  contract_id                 NUMBER(19)         CONSTRAINT fk_attachments_contract REFERENCES contracts (id) ON DELETE CASCADE,
  document_type               VARCHAR2(60 CHAR)  NOT NULL,
  file_name                   VARCHAR2(200 CHAR) NOT NULL,
  content_type                VARCHAR2(150 CHAR) NOT NULL,
  size_bytes                  NUMBER(19)         NOT NULL,
  description                 VARCHAR2(300 CHAR),
  uploaded_at                 TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  uploaded_by_person_id       NUMBER(19)         REFERENCES people (id),
  created_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_by_person_id        NUMBER(19)         REFERENCES people (id),
  updated_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by_person_id        NUMBER(19)         REFERENCES people (id),
  last_reviewed_at            TIMESTAMP(3) WITH TIME ZONE,
  last_reviewed_by_person_id  NUMBER(19)         REFERENCES people (id),
  CONSTRAINT ck_attachments_owner CHECK (
    (CASE WHEN application_id IS NULL THEN 0 ELSE 1 END) + (CASE WHEN project_id IS NULL THEN 0 ELSE 1 END) +
    (CASE WHEN team_id IS NULL THEN 0 ELSE 1 END) + (CASE WHEN technology_id IS NULL THEN 0 ELSE 1 END) +
    (CASE WHEN risk_id IS NULL THEN 0 ELSE 1 END) + (CASE WHEN escalation_id IS NULL THEN 0 ELSE 1 END) +
    (CASE WHEN decision_id IS NULL THEN 0 ELSE 1 END) + (CASE WHEN demand_id IS NULL THEN 0 ELSE 1 END) +
    (CASE WHEN contract_id IS NULL THEN 0 ELSE 1 END) = 1),
  CONSTRAINT ck_attachments_size CHECK (size_bytes > 0 AND size_bytes <= 20971520),
  -- Executables, scripts, HTML and SVG are refused (the application validates the same list).
  CONSTRAINT ck_attachments_extension CHECK (REGEXP_LIKE(LOWER(file_name), '\.(pdf|docx?|odt|rtf|txt|md|xlsx?|ods|csv|pptx?|odp|png|jpe?g|gif|webp|vsdx|drawio|zip)$'))
);
