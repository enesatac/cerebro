-- The reference shown to users (TLP-0012) is derived from the id by the application.
CREATE TABLE demands (                               -- Demand
  id                          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title                       VARCHAR2(200 CHAR) NOT NULL,
  type                        VARCHAR2(60 CHAR)  NOT NULL,
  business_unit_id            NUMBER(19)         NOT NULL CONSTRAINT fk_demands_unit REFERENCES business_units (id),
  requester_person_id         NUMBER(19)         NOT NULL CONSTRAINT fk_demands_requester REFERENCES people (id),
  sponsor_person_id           NUMBER(19)         CONSTRAINT fk_demands_sponsor REFERENCES people (id),
  problem                     CLOB               NOT NULL,
  proposed_solution           CLOB,
  expected_benefits           CLOB               NOT NULL,
  urgency                     VARCHAR2(60 CHAR)  NOT NULL,
  desired_date                DATE,
  deadline_reason             VARCHAR2(500 CHAR),
  regulatory                  NUMBER(1)          DEFAULT 0 NOT NULL,
  affected_users              NUMBER(10),
  estimated_budget            NUMBER(14, 2),
  currency                    VARCHAR2(10 CHAR)  DEFAULT 'TRY' NOT NULL,
  status                      VARCHAR2(60 CHAR)  DEFAULT 'submitted' NOT NULL,
  submitted_at                TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  -- Assessment (1 = lowest … 5 = highest, effort 1 = weeks … 5 = a year or more)
  business_value              NUMBER(1),
  strategic_fit               NUMBER(1),
  time_criticality            NUMBER(1),
  risk_reduction              NUMBER(1),
  effort                      NUMBER(1),
  priority                    VARCHAR2(60 CHAR),
  assessor_person_id          NUMBER(19)         CONSTRAINT fk_demands_assessor REFERENCES people (id) ON DELETE SET NULL,
  planned_start               DATE,
  planned_end                 DATE,
  decision_note               VARCHAR2(2000 CHAR),
  -- The project the demand became, deleting the project later unlinks it.
  project_id                  NUMBER(19)         CONSTRAINT fk_demands_project REFERENCES projects (id) ON DELETE SET NULL,
  created_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_by_person_id        NUMBER(19)         REFERENCES people (id),
  updated_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by_person_id        NUMBER(19)         REFERENCES people (id),
  last_reviewed_at            TIMESTAMP(3) WITH TIME ZONE,
  last_reviewed_by_person_id  NUMBER(19)         REFERENCES people (id),
  CONSTRAINT ck_demands_regulatory CHECK (regulatory IN (0, 1)),
  CONSTRAINT ck_demands_users CHECK (affected_users >= 0),
  CONSTRAINT ck_demands_budget CHECK (estimated_budget >= 0),
  CONSTRAINT ck_demands_scores CHECK (
    (business_value IS NULL OR business_value BETWEEN 1 AND 5) AND
    (strategic_fit IS NULL OR strategic_fit BETWEEN 1 AND 5) AND
    (time_criticality IS NULL OR time_criticality BETWEEN 1 AND 5) AND
    (risk_reduction IS NULL OR risk_reduction BETWEEN 1 AND 5) AND
    (effort IS NULL OR effort BETWEEN 1 AND 5)),
  CONSTRAINT ck_demands_plan CHECK (planned_end IS NULL OR planned_start IS NULL OR planned_end >= planned_start),
  -- The workflow rules the application enforces (system codes of `demandStatuses`).
  CONSTRAINT ck_demands_note CHECK (status NOT IN ('rejected', 'needs-info') OR decision_note IS NOT NULL),
  CONSTRAINT ck_demands_priority CHECK (status NOT IN ('approved', 'scheduled', 'converted') OR priority IS NOT NULL),
  CONSTRAINT ck_demands_scheduled CHECK (status NOT IN ('scheduled', 'converted') OR (planned_start IS NOT NULL AND planned_end IS NOT NULL))
);
CREATE INDEX ix_demands_status ON demands (status);
