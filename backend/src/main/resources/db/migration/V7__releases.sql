-- Production releases (canlı geçişler) of applications, optionally delivered by a project. A
-- release goes with its application; deleting a project only clears the link; its owner cannot
-- be deleted (the application blocks it, the foreign key restricts it). The privileges and value
-- lists are seeded by V8.

CREATE TABLE releases (                              -- Release
  id                          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  release_number              VARCHAR2(40 CHAR)   NOT NULL,           -- change / release number, unique (case-insensitive, checked by the service)
  title                       VARCHAR2(200 CHAR)  NOT NULL,
  application_id              NUMBER(19)          NOT NULL CONSTRAINT fk_releases_application REFERENCES applications (id) ON DELETE CASCADE,
  project_id                  NUMBER(19)          CONSTRAINT fk_releases_project REFERENCES projects (id) ON DELETE SET NULL,
  type                        VARCHAR2(60 CHAR)   NOT NULL,           -- master data releaseTypes
  status                      VARCHAR2(60 CHAR)   NOT NULL,           -- master data releaseStatuses
  planned_date                DATE                NOT NULL,
  start_time                  VARCHAR2(5 CHAR),                       -- HH:mm; end before start = past midnight
  end_time                    VARCHAR2(5 CHAR),
  version                     VARCHAR2(40 CHAR),
  owner_person_id             NUMBER(19)          CONSTRAINT fk_releases_owner REFERENCES people (id),
  service_interruption        NUMBER(1)           DEFAULT 0 NOT NULL,
  description                 CLOB,
  rollback_plan               CLOB,
  outcome_note                CLOB,
  created_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_by_person_id        NUMBER(19)          REFERENCES people (id),
  updated_at                  TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by_person_id        NUMBER(19)          REFERENCES people (id),
  last_reviewed_at            TIMESTAMP(3) WITH TIME ZONE,
  last_reviewed_by_person_id  NUMBER(19)          REFERENCES people (id),
  CONSTRAINT ck_releases_interruption CHECK (service_interruption IN (0, 1)),
  CONSTRAINT ck_releases_start CHECK (start_time IS NULL OR REGEXP_LIKE(start_time, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
  CONSTRAINT ck_releases_end CHECK (end_time IS NULL OR REGEXP_LIKE(end_time, '^([01][0-9]|2[0-3]):[0-5][0-9]$'))
);
CREATE INDEX ix_releases_date ON releases (planned_date);
CREATE INDEX ix_releases_application ON releases (application_id, planned_date);
CREATE INDEX ix_releases_project ON releases (project_id);
CREATE INDEX ix_releases_owner ON releases (owner_person_id);
