-- Procurement tracker: the process of each purchase (a contract) as ordered steps with planned and
-- actual dates, and a log of notes. Both go with their contract; people in them cannot be deleted
-- (the application blocks it, the foreign keys restrict it). The privileges and value lists the
-- tracker needs are seeded by V6.

CREATE TABLE procurement_steps (                     -- ProcurementStep
  id               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id      NUMBER(19)          NOT NULL CONSTRAINT fk_proc_steps_contract REFERENCES contracts (id) ON DELETE CASCADE,
  sort_order       NUMBER(10)          NOT NULL,          -- position in the process
  step_type        VARCHAR2(60 CHAR)   NOT NULL,          -- master data procurementSteps
  status           VARCHAR2(60 CHAR)   NOT NULL,          -- master data procurementStepStatuses
  owner_person_id  NUMBER(19)          CONSTRAINT fk_proc_steps_owner REFERENCES people (id),
  planned_start    DATE,
  planned_end      DATE,
  actual_start     DATE,
  actual_end       DATE,
  note             VARCHAR2(1000 CHAR),
  CONSTRAINT ck_proc_steps_planned CHECK (planned_end IS NULL OR planned_start IS NULL OR planned_end >= planned_start),
  CONSTRAINT ck_proc_steps_actual CHECK (actual_end IS NULL OR actual_start IS NULL OR actual_end >= actual_start)
);
CREATE INDEX ix_proc_steps_contract ON procurement_steps (contract_id, sort_order);
CREATE INDEX ix_proc_steps_owner ON procurement_steps (owner_person_id);

CREATE TABLE procurement_notes (                     -- ProcurementNote
  id                NUMBER(19)                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id       NUMBER(19)                   NOT NULL CONSTRAINT fk_proc_notes_contract REFERENCES contracts (id) ON DELETE CASCADE,
  created_at        TIMESTAMP(3) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  author_person_id  NUMBER(19)                   CONSTRAINT fk_proc_notes_author REFERENCES people (id),
  note_text         CLOB                         NOT NULL,
  internal          NUMBER(1)                    DEFAULT 0 NOT NULL,  -- procurement team only
  CONSTRAINT ck_proc_notes_internal CHECK (internal IN (0, 1))
);
CREATE INDEX ix_proc_notes_contract ON procurement_notes (contract_id, created_at);
CREATE INDEX ix_proc_notes_author ON procurement_notes (author_person_id);
